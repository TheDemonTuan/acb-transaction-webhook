// Command voice-catalog compiles immutable Vietnamese recipes and exports exact-profile audio transcripts.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/thedemontuan/acb-transaction-webhook/internal/voicecopy"
)

const catalogDirectory = "internal/voicecopy/catalog"

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "voice-catalog:", err)
		os.Exit(1)
	}
}

func run(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("voice-catalog", flag.ContinueOnError)
	compile := flags.Bool("compile", false, "compile source, generated catalog, and complete semantic-review batches")
	check := flags.Bool("check", false, "check generated bytes, fixtures, and all 10000 semantic approvals")
	audio := flags.Bool("audio-inputs", false, "export approved Go-formatted transcripts for the voice pack builder")
	profilePath := flags.String("profile", "", "resolved EDGE_ONLY profile JSON for --audio-inputs")
	outputPath := flags.String("output", "", "output JSON file for --audio-inputs")
	if err := flags.Parse(args); err != nil {
		return err
	}
	operations := 0
	for _, enabled := range []bool{*compile, *check, *audio} {
		if enabled {
			operations++
		}
	}
	if operations != 1 || flags.NArg() != 0 {
		return errors.New("choose exactly one of --compile, --check, --audio-inputs")
	}
	if !*audio && (*profilePath != "" || *outputPath != "") {
		return errors.New("--profile and --output require --audio-inputs")
	}
	if *audio && (*profilePath == "" || *outputPath == "") {
		return errors.New("--audio-inputs requires --profile and --output")
	}
	source, err := os.ReadFile(filepath.Join(catalogDirectory, "source.v1.json"))
	if err != nil {
		return err
	}
	catalog, err := voicecopy.CompileCatalog(source)
	if err != nil {
		return err
	}
	if *compile {
		if err := compileFiles(catalog); err != nil {
			return err
		}
		fmt.Fprintln(stdout, "Compiled 10000 mechanically validated unique tails, 600 fragments, and six unchanged classic presets. Semantic decisions were preserved only for unchanged batch hashes; run --check after full text review.")
		return nil
	}
	if err := checkFiles(catalog); err != nil {
		return err
	}
	if *check {
		fmt.Fprintln(stdout, "Catalog v1: 10000 approved unique tails, 1250 per style/band, 600 fragments, six exact classic presets; generated bytes, all review batches, and amount fixtures match.")
		return nil
	}
	profile, suppliedKey, err := readProfile(*profilePath)
	if err != nil {
		return err
	}
	inputs, err := voicecopy.ExportAudioInputs(profile)
	if err != nil {
		return err
	}
	if suppliedKey != "" && inputs.SynthesisKey != suppliedKey {
		return errors.New("profile synthesisKey does not match exact voice/rate/pitch")
	}
	raw, err := voicecopy.MarshalCatalog(inputs)
	if err != nil {
		return err
	}
	if err := writeFile(*outputPath, raw); err != nil {
		return err
	}
	fmt.Fprintf(stdout, "Exported %d clips for %s; no synthesis or publication performed.\n", len(inputs.Clips), inputs.SynthesisKey)
	return nil
}

func readEvidence() (voicecopy.CatalogReviewEvidence, error) {
	var evidence voicecopy.CatalogReviewEvidence
	raw, err := os.ReadFile(filepath.Join(catalogDirectory, "review.v1.json"))
	if err != nil {
		return evidence, err
	}
	err = decodeJSON(raw, &evidence)
	return evidence, err
}

func compileFiles(catalog voicecopy.VoiceCatalog) error {
	old, err := readEvidence()
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read existing review evidence: %w", err)
	}
	previous := make(map[string]voicecopy.CatalogReviewDecision, len(old.Batches))
	for _, decision := range old.Batches {
		previous[decision.ID] = decision
	}
	evidence := voicecopy.CatalogReviewEvidence{Version: voicecopy.CatalogVersion, Batches: make([]voicecopy.CatalogReviewDecision, 0, 80)}
	batches := voicecopy.BuildCatalogReviewBatches(catalog)
	for _, batch := range batches {
		digest := voicecopy.CatalogBatchDigest(batch)
		decision, exists := previous[batch.ID]
		if !exists || decision.SHA256 != digest || decision.RecipeCount != len(batch.Recipes) {
			decision = voicecopy.CatalogReviewDecision{ID: batch.ID, SHA256: digest, RecipeCount: len(batch.Recipes), Decision: "pending", RejectedRecipeIDs: []string{}}
		}
		evidence.Batches = append(evidence.Batches, decision)
		if decision.Decision == "approved" {
			evidence.ApprovedUnique += len(batch.Recipes)
		}
		if decision.Decision == "rejected" {
			evidence.RejectedCount += len(decision.RejectedRecipeIDs)
		}
	}
	if err := voicecopy.ValidateCatalogReview(catalog, evidence, false); err != nil {
		return err
	}
	raw, err := voicecopy.MarshalCatalog(catalog)
	if err != nil {
		return err
	}
	if err := writeFile(filepath.Join(catalogDirectory, "catalog.v1.json"), raw); err != nil {
		return err
	}
	for _, batch := range batches {
		raw, err := voicecopy.MarshalCatalog(batch)
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(catalogDirectory, "review-batches", batch.ID+".json"), raw); err != nil {
			return err
		}
	}
	raw, err = voicecopy.MarshalCatalog(evidence)
	if err != nil {
		return err
	}
	return writeFile(filepath.Join(catalogDirectory, "review.v1.json"), raw)
}

func checkFiles(catalog voicecopy.VoiceCatalog) error {
	if err := voicecopy.CheckAmountFixtures(); err != nil {
		return err
	}
	expected, err := voicecopy.MarshalCatalog(catalog)
	if err != nil {
		return err
	}
	if len(expected) > 4*1024*1024 {
		return errors.New("catalog exceeds 4 MiB")
	}
	actual, err := os.ReadFile(filepath.Join(catalogDirectory, "catalog.v1.json"))
	if err != nil {
		return err
	}
	if !bytes.Equal(expected, actual) {
		return errors.New("generated catalog differs; run --compile")
	}
	for _, batch := range voicecopy.BuildCatalogReviewBatches(catalog) {
		expected, err := voicecopy.MarshalCatalog(batch)
		if err != nil {
			return err
		}
		actual, err := os.ReadFile(filepath.Join(catalogDirectory, "review-batches", batch.ID+".json"))
		if err != nil {
			return err
		}
		if !bytes.Equal(expected, actual) {
			return fmt.Errorf("review batch %s differs; run --compile", batch.ID)
		}
	}
	evidence, err := readEvidence()
	if err != nil {
		return err
	}
	return voicecopy.ValidateCatalogReview(catalog, evidence, true)
}

func readProfile(path string) (voicecopy.AudioInputProfile, string, error) {
	var profile struct {
		ProviderMode   string  `json:"providerMode"`
		EdgeVoice      string  `json:"edgeVoice"`
		VoiceID        string  `json:"voiceId"`
		Rate           float64 `json:"rate"`
		PitchHz        int     `json:"pitchHz"`
		SynthesisKey   string  `json:"synthesisKey"`
		CatalogVersion string  `json:"catalogVersion"`
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return voicecopy.AudioInputProfile{}, "", err
	}
	// Resolved profiles contain read-only fields; only these synthesis fields are consumed.
	if err := decodeJSON(raw, &profile); err != nil {
		return voicecopy.AudioInputProfile{}, "", err
	}
	if profile.ProviderMode != "" && profile.ProviderMode != "EDGE_ONLY" {
		return voicecopy.AudioInputProfile{}, "", errors.New("audio packs require EDGE_ONLY")
	}
	if profile.CatalogVersion != "" && profile.CatalogVersion != voicecopy.CatalogVersion {
		return voicecopy.AudioInputProfile{}, "", errors.New("unsupported catalog version")
	}
	voice := profile.EdgeVoice
	if voice == "" {
		voice = profile.VoiceID
	}
	if profile.EdgeVoice != "" && profile.VoiceID != "" && profile.EdgeVoice != profile.VoiceID {
		return voicecopy.AudioInputProfile{}, "", errors.New("edgeVoice and voiceId disagree")
	}
	return voicecopy.AudioInputProfile{VoiceID: voice, Rate: profile.Rate, PitchHz: profile.PitchHz}, profile.SynthesisKey, nil
}

func decodeJSON(raw []byte, target any) error {
	decoder := json.NewDecoder(bytes.NewReader(raw))
	if err := decoder.Decode(target); err != nil {
		return err
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return errors.New("trailing JSON")
	}
	return nil
}

func writeFile(path string, raw []byte) error {
	if strings.TrimSpace(path) == "" {
		return errors.New("output path is empty")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, raw, 0644)
}
